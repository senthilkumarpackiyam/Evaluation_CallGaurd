"""Phase 1: check the golden dataset against CallGuard's frozen data before it goes to LangSmith.

Run it with:  uv run scripts/check_dataset.py
Checks the group mix (20/12/6/2), the fields, every expected CVE, every CVE a reference mentions, the refusal reasons
against CallGuard's product list, and the two freshness answers against the data's date. When there are no problems,
it rewrites dataset/README.md, the table of all 40 cases.
"""

import sys
from collections import Counter

from callguard_eval.dataset import DATASET_FILE, GROUPS, load_cases, load_records, problems

TABLE_FILE = DATASET_FILE.parent / "README.md"


def readable(question, limit=110):
    """The question as one short, printable line (A2 is deliberately full of control characters)."""
    text = " ".join("".join(ch if ch.isprintable() else " " for ch in question).split())
    text = text if len(text) <= limit else text[:limit - 1] + "…"
    for raw, escaped in [("|", "\\|"), ("*", "\\*"), ("<", "&lt;"), (">", "&gt;")]:  # so GitHub shows it as text
        text = text.replace(raw, escaped)
    return text


def write_table(cases):
    lines = ["# The golden dataset", "",
             "40 cases in [`golden.toml`](golden.toml), uploaded to LangSmith as `callguard-golden-40` (one split per "
             "group). Expected answers come from CallGuard's data, frozen at 2026-10-20 18:44 UTC. "
             "Generated by `scripts/check_dataset.py`.", ""]
    for group in GROUPS:
        in_group = [c for c in cases if c["group"] == group]
        lines += [f"## {group} ({len(in_group)})", "", "| ID | Type | Question | Expect | CVEs | Tests |",
                  "|---|---|---|---|---|---|"]
        for c in in_group:
            expect = c["expect"] + (f" ({c['reason']})" if c.get("reason") else "")
            tests = c["tests"] + (f" *Known issue: {c['known_issue']}*" if c.get("known_issue") else "")
            lines.append(f"| {c['id']}{'' if c['source'] == 'exam' else ' 🆕'} | {c['type']} | {readable(c['question'])} "
                         f"| {expect} | {len(c['cves']) or '–'} | {tests} |")
        lines.append("")
    lines.append("🆕 = written for this evaluation; the rest come from CallGuard's 25-question exam.")
    TABLE_FILE.write_text("\n".join(lines) + "\n")


def main():
    cases, records = load_cases(), load_records()
    print(f"{len(cases)} cases, checked against {len(records)} CVE records\n")
    print(f"{'group':14} {'cases':>5}  types")
    for group in GROUPS:
        in_group = [c for c in cases if c["group"] == group]
        types = Counter(c["type"] for c in in_group)
        print(f"{group:14} {len(in_group):>5}  " + ", ".join(f"{t} {n}" for t, n in types.most_common()))
    sources = Counter(c["source"] for c in cases)
    expects = Counter(c["expect"] for c in cases)
    expected = sum(len(c["cves"]) for c in cases)
    print(f"\n{sources['exam']} from CallGuard's exam, {sources['new']} new; "
          + ", ".join(f"{n} {e}" for e, n in expects.most_common())
          + f"; {expected} expected CVEs ({len({cve for c in cases for cve in c['cves']})} different)")
    longest = max(cases, key=lambda c: len(c["question"]))
    print(f"Longest question: {longest['id']}, {len(longest['question'])} characters")

    found = problems(cases, records)
    print("\n" + ("\n".join(f"❌ {p}" for p in found) if found else "✅ No problems: ready to upload"))
    if not found:
        write_table(cases)
        print(f"Wrote {TABLE_FILE.relative_to(TABLE_FILE.parents[1])}")
    sys.exit(1 if found else 0)


if __name__ == "__main__":
    main()
